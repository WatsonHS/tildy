#!/usr/bin/env bash
# 启动一个隔离的交互式 zsh，用于试用开发构建的 tildy，不修改 ~/.zshrc 或 $HOME 下的任何文件。
#
# 用法：scripts/dev-shell.sh [--release] [--plugins] [--config PATH] [--fake] [--print-zshrc]
#
#   --release       使用 target/release/tildy（默认 target/debug/tildy）
#   --plugins       加载 ~/.oh-my-zsh/custom/plugins 中的 zsh-autosuggestions、
#                   zsh-syntax-highlighting，以及 fzf 的 Zsh 集成（若已安装）
#   --config PATH   设置 TILDY_CONFIG=PATH
#   --fake          不使用 tildy 二进制：TILDY_BACKEND 指向 bench/fake-backend.sh，直接 source shell/zsh/tildy.zsh
#   --print-zshrc   只把生成的临时 .zshrc 打印到标准输出后退出（不创建临时目录）
#
# 临时 ZDOTDIR 位于 $TMPDIR 下；调试日志（TILDY_DEBUG_LOG）与历史文件都在该目录中，退出后保留以便查看。

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PLUGIN_DIR="${TILDY_TEST_PLUGIN_DIR:-$HOME/.oh-my-zsh/custom/plugins}"

profile=debug
plugins=0
config=""
fake=0
print_only=0

say() { printf '[dev-shell] %s\n' "$*" >&2; }
die() { printf '[dev-shell] 错误：%s\n' "$*" >&2; exit 2; }

usage() {
  awk 'NR > 1 && /^$/ { exit } NR > 1 { print }' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --release) profile=release ;;
    --plugins) plugins=1 ;;
    --config)
      [[ $# -ge 2 ]] || die "--config 需要一个路径参数"
      config="$2"
      shift
      ;;
    --config=*) config="${1#--config=}" ;;
    --fake) fake=1 ;;
    --print-zshrc) print_only=1 ;;
    -h|--help) usage; exit 0 ;;
    *) die "未知参数：$1（用 --help 查看用法）" ;;
  esac
  shift
done

BIN="$REPO/target/$profile/tildy"
FAKE_BACKEND="$REPO/bench/fake-backend.sh"
SHELL_FILE="$REPO/shell/zsh/tildy.zsh"

if [[ -n "$config" ]]; then
  case "$config" in
    /*) ;;
    *) config="$PWD/$config" ;;
  esac
fi

if (( fake )); then
  [[ -r "$SHELL_FILE" ]] || die "找不到 $SHELL_FILE"
  [[ -x "$FAKE_BACKEND" ]] || die "找不到可执行的假后端 $FAKE_BACKEND"
elif (( ! print_only )); then
  [[ -x "$BIN" ]] || die "找不到 ${BIN}；请先在项目根目录运行 cargo build$( [[ $profile == release ]] && echo ' --release')，或使用 --fake"
fi

# 生成 .zshrc 的内容到标准输出。参数：调试日志路径。
emit_zshrc() {
  local debug_log="$1"
  printf '# Generated by scripts/dev-shell.sh. Isolated: ~/.zshrc is not read.\n'
  printf 'HISTFILE=%q\n' "$(dirname "$debug_log")/.zsh_history"
  printf "PS1='%%~ %%# '\n"
  printf 'export TILDY_DEBUG_LOG=%q\n' "$debug_log"
  if [[ -n "$config" ]]; then
    printf 'export TILDY_CONFIG=%q\n' "$config"
  fi
  if (( plugins )); then
    printf 'if [[ -r %q ]]; then source %q; fi\n' \
      "$PLUGIN_DIR/zsh-autosuggestions/zsh-autosuggestions.zsh" \
      "$PLUGIN_DIR/zsh-autosuggestions/zsh-autosuggestions.zsh"
    printf 'if [[ -r %q ]]; then source %q; fi\n' \
      "$PLUGIN_DIR/zsh-syntax-highlighting/zsh-syntax-highlighting.zsh" \
      "$PLUGIN_DIR/zsh-syntax-highlighting/zsh-syntax-highlighting.zsh"
    printf 'if command -v fzf >/dev/null 2>&1; then source %q || print -u2 "fzf integration unavailable"; fi\n' "$REPO/scripts/fzf.zsh"
  fi
  if (( fake )); then
    printf 'export TILDY_BACKEND=%q\n' "$FAKE_BACKEND"
    printf 'source %q\n' "$SHELL_FILE"
  else
    printf 'eval "$(%q init zsh)"\n' "$BIN"
  fi
}

if (( print_only )); then
  say "打印模式：临时目录以占位符表示，不创建任何文件。"
  emit_zshrc "/tmp/tildy-dev.XXXXXX/tildy-debug.log"
  exit 0
fi

say "仓库：$REPO"
if (( fake )); then
  say "模式：假后端（TILDY_BACKEND=${FAKE_BACKEND}），直接 source shell/zsh/tildy.zsh，不使用 tildy 二进制。"
else
  say "模式：tildy 二进制 ${BIN}（eval \"\$(tildy init zsh)\"）。"
fi
(( plugins )) && say "插件：从 $PLUGIN_DIR 加载 autosuggestions、syntax-highlighting；若有 fzf 则加载其 zsh 键绑定。"
[[ -n "$config" ]] && say "配置：TILDY_CONFIG=$config"

dev_dir="$(mktemp -d "${TMPDIR:-/tmp}/tildy-dev.XXXXXX")"
debug_log="$dev_dir/tildy-debug.log"
: > "$debug_log"
emit_zshrc "$debug_log" > "$dev_dir/.zshrc"
say "临时 ZDOTDIR：${dev_dir}（生成的 .zshrc 在其中，退出后保留）"
say "调试日志（TILDY_DEBUG_LOG）：$debug_log"
say "启动交互式 zsh；输入 exit 结束。不会读取 ~/.zshrc。"

export ZDOTDIR="$dev_dir"
exec zsh -i
